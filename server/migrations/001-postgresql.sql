CREATE TABLE users (
  id TEXT PRIMARY KEY,
  email TEXT UNIQUE NOT NULL,
  is_admin INTEGER NOT NULL DEFAULT 0 CHECK (is_admin IN (0,1)),
  created_at TEXT NOT NULL
);
CREATE TABLE ideas (
  id TEXT PRIMARY KEY,
  user_id TEXT NOT NULL REFERENCES users(id),
  title TEXT NOT NULL,
  problem TEXT NOT NULL,
  solution TEXT NOT NULL,
  skills TEXT NOT NULL,
  image TEXT,
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL
);
CREATE TABLE likes (
  user_id TEXT NOT NULL REFERENCES users(id),
  idea_id TEXT NOT NULL REFERENCES ideas(id) ON DELETE CASCADE,
  PRIMARY KEY (user_id,idea_id)
);
CREATE TABLE votes (
  user_id TEXT NOT NULL REFERENCES users(id),
  idea_id TEXT NOT NULL REFERENCES ideas(id) ON DELETE CASCADE,
  round INTEGER NOT NULL,
  PRIMARY KEY (user_id,idea_id,round)
);
CREATE TABLE settings (
  id INTEGER PRIMARY KEY CHECK (id=1),
  mode TEXT NOT NULL DEFAULT 'closed' CHECK (mode IN ('open','closed','scheduled')),
  starts_at TEXT,
  ends_at TEXT,
  max_votes INTEGER NOT NULL DEFAULT 2 CHECK (max_votes BETWEEN 1 AND 100),
  round INTEGER NOT NULL DEFAULT 1,
  show_timer INTEGER NOT NULL DEFAULT 1 CHECK (show_timer IN (0,1)),
  top_votes INTEGER NOT NULL DEFAULT 0 CHECK (top_votes IN (0,1)),
  top_likes INTEGER NOT NULL DEFAULT 0 CHECK (top_likes IN (0,1)),
  innovation_award INTEGER NOT NULL DEFAULT 0 CHECK (innovation_award IN (0,1)),
  peoples_award INTEGER NOT NULL DEFAULT 0 CHECK (peoples_award IN (0,1)),
  submission_mode TEXT NOT NULL DEFAULT 'open' CHECK (submission_mode IN ('open','closed','scheduled')),
  submission_ends_at TEXT,
  show_welcome INTEGER NOT NULL DEFAULT 1 CHECK (show_welcome IN (0,1)),
  voting_started_at TEXT
);
